/**
 * CRUCION Registration Flow Dedicated Test Suite
 * Validates new user registration, duplicate email handling, validation errors,
 * organization creation in transaction, and sign-in authentication.
 */

import path from "path";
import dotenv from "dotenv";
dotenv.config({ path: path.resolve(process.cwd(), ".env.local"), override: true });

import assert from "assert";
import bcrypt from "bcryptjs";
import { db } from "../src/lib/db";
import { SignupFormSchema } from "../src/lib/auth-definitions";

async function runRegistrationTests() {
  console.log("=================================================");
  console.log("CRUCION REGISTRATION WORKFLOW VERIFICATION");
  console.log("=================================================");

  const timestamp = Date.now();
  const testEmail = `enterprise_${timestamp}@crucion.io`;
  const rawPassword = "CrucionSecuredPass2026!#";
  const orgName = "Apex Cloud Intelligence";

  // Test 1: Validation checks (invalid email, weak password)
  console.log("\n[TEST 1] Form validation & Zod schema checks...");
  const invalidEmailResult = SignupFormSchema.safeParse({
    name: "John Doe",
    email: "not-an-email",
    password: rawPassword,
    organization: orgName,
  });
  assert.strictEqual(invalidEmailResult.success, false, "Invalid email must fail validation");

  const weakPasswordResult = SignupFormSchema.safeParse({
    name: "John Doe",
    email: testEmail,
    password: "123",
    organization: orgName,
  });
  assert.strictEqual(weakPasswordResult.success, false, "Weak password (<8 chars) must fail validation");
  console.log("✓ Server-side validation constraints verified");

  // Test 2: New user registration with atomic organization creation
  console.log("\n[TEST 2] Genuine PostgreSQL User & Organization registration...");
  const passwordHash = await bcrypt.hash(rawPassword, 12);
  const { user, organization } = await db.users.create({
    email: testEmail,
    name: "Jane Chief Architect",
    passwordHash,
    organizationName: orgName,
  });

  assert(user.id, "User ID must be generated by database");
  assert.strictEqual(user.email, testEmail.toLowerCase());
  assert.strictEqual(user.emailVerified, false, "Email must be unverified initially");
  assert.strictEqual(organization.name, orgName);
  console.log("✓ User created in PostgreSQL:", user.id);
  console.log("✓ Organization created in transaction:", organization.id);

  // Test 3: Duplicate email prevention
  console.log("\n[TEST 3] Duplicate email rejection check...");
  let duplicateCaught = false;
  try {
    await db.users.create({
      email: testEmail.toUpperCase(), // Case-insensitive test
      name: "Duplicate User",
      passwordHash,
      organizationName: "Another Org",
    });
  } catch (err: unknown) {
    duplicateCaught = true;
    assert((err as Error).message.includes("already exists"), "Error message must state account exists");
  }
  assert.strictEqual(duplicateCaught, true, "Duplicate email must be rejected");
  console.log("✓ Duplicate email rejection verified");

  // Test 4: Email verification flow
  console.log("\n[TEST 4] Email verification token and verification update...");
  const verifyToken = "test_verify_token_" + timestamp;
  const expiry = new Date(Date.now() + 24 * 60 * 60 * 1000);
  await db.users.setVerificationToken(user.id, verifyToken, expiry);

  const foundByToken = await db.users.findByVerificationToken(verifyToken);
  assert(foundByToken && foundByToken.id === user.id, "User must be found by active verification token");

  const verifiedUser = await db.users.verifyEmail(user.id);
  assert.strictEqual(verifiedUser.emailVerified, true, "emailVerified flag must be true after verification");
  assert.strictEqual(verifiedUser.verificationToken, null, "verificationToken must be cleared");
  console.log("✓ Email verification workflow verified in PostgreSQL");

  // Test 5: Sign-in credential check
  console.log("\n[TEST 5] Sign-in authentication & password matching...");
  const lookupUser = await db.users.findByEmail(testEmail);
  assert(lookupUser, "Registered user must be found by email");
  const validPasswordMatch = await bcrypt.compare(rawPassword, lookupUser.passwordHash);
  assert.strictEqual(validPasswordMatch, true, "Valid password must authenticate");
  const invalidPasswordMatch = await bcrypt.compare("WrongPassword999!", lookupUser.passwordHash);
  assert.strictEqual(invalidPasswordMatch, false, "Invalid password must be rejected");
  console.log("✓ Sign-in authentication verified against PostgreSQL");

  // Clean up
  await db.users.deleteAccount(user.id);
  console.log("\n✓ Cleaned up test user record from PostgreSQL");

  console.log("\n=================================================");
  console.log("ALL REGISTRATION WORKFLOW TESTS PASSED ✓");
  console.log("=================================================");
}

runRegistrationTests().catch((err) => {
  console.error("Registration tests failed:", err);
  process.exit(1);
});
